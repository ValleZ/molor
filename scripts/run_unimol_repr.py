"""Extract Uni-Mol molecular representations for the library.

Every percept model here is trained on GS-LF, so each one's geometry is shaped
by the same 4983 molecules and the same 138 descriptors. Uni-Mol is the first
representation in this project that has never seen an odour label: it is a
transformer pretrained on 209M 3D conformers, and its CLS embedding is a
general-purpose molecular descriptor.

That makes it the sharpest available test of where the similarity structure
comes from. If a label-free 3D embedding matches human descriptor overlap about
as well as a model trained on those descriptors, then most of what the trained
models recover is plain chemistry. If it does markedly worse, the odour labels
are contributing something a general chemical prior does not have.

Conformers are generated by RDKit inside unimol_tools from SMILES, so no
external 3D input is needed. Runs under .venv-unimol.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default="library/input/expanded_materials.csv")
    ap.add_argument("--out", default="artifacts/unimol_repr.npz")
    ap.add_argument("--model", default="unimolv1")
    ap.add_argument("--size", default="84m")
    args = ap.parse_args()

    from unimol_tools import UniMolRepr

    rows = list(csv.DictReader(
        open(ROOT / args.csv, newline="", encoding="utf-8-sig")))
    names = [r["name"] for r in rows]
    smis = [r["smiles"] for r in rows]
    print(f"[unimol] {len(smis)} materials, model {args.model}/{args.size}",
          flush=True)

    rep = UniMolRepr(data_type="molecule", remove_hs=False,
                     model_name=args.model, model_size=args.size)

    # Conformer generation fails on some molecules; keep names aligned by
    # embedding one at a time rather than trusting a silent length match.
    keep, embs = [], []
    for n, s in zip(names, smis):
        try:
            out = rep.get_repr([s], return_atomic_reprs=False)
            v = np.asarray(out["cls_repr"], dtype=float).reshape(1, -1)
        except Exception as exc:  # noqa: BLE001 - report and skip, never guess
            print(f"  skipped {n}: {type(exc).__name__}: {exc}", flush=True)
            continue
        keep.append(n)
        embs.append(v[0])

    if not embs:
        raise SystemExit("no representations produced")
    E = np.vstack(embs)
    print(f"[unimol] {E.shape[0]} of {len(names)} embedded, dim {E.shape[1]}")

    dest = ROOT / args.out
    with open(dest, "wb") as fh:
        np.savez(fh, names=np.array(keep, dtype=object), emb=E)
    print(f"[unimol] wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
