"""Write the descriptor vocabulary to a file, with how usable each one is.

The question "what can I ask for?" had no answer in this repository: the 138
descriptor names existed only inside artifacts/percepts_fp3.json, as a JSON
key nobody would read, and the vocabulary is the first thing anyone needs when
writing a target by hand or deciding whether an idea is expressible at all.

Three columns decide whether a descriptor is worth asking for:

*Training molecules.* How many of the 4983 labelled molecules carry the label.
Below about 80 the model has seen too few examples to place a request
reliably; ozone, the only marine-ish word in the set, has 39.

*Library carriers.* How many of the library's materials score two standard
deviations or more above the library mean on it. A descriptor with no carrier
cannot be delivered however well the model understands it -- the convex hull
of the palette is the real limit, not the vocabulary.

*The strongest carrier.* The material to reach for, which is usually the
answer the asker actually wanted.

    python scripts/descriptor_list.py
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--percepts", default="artifacts/percepts_fp3.json")
    ap.add_argument("--train", default="data/percept/gslf_hierarchical.csv")
    ap.add_argument("--out", default="data/percept/descriptors.csv")
    ap.add_argument("--md", default="data/percept/descriptors.md")
    args = ap.parse_args()

    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        pass

    pj = json.loads((ROOT / args.percepts).read_text(encoding="utf-8"))
    desc = list(pj["descriptors"])
    names = list(pj["molecules"])
    X = np.asarray(pj["probs"], float)
    mu, sd = X.mean(0), X.std(0) + 1e-9
    Z = (X - mu) / sd

    support = {}
    tpath = ROOT / args.train
    if tpath.is_file():
        rows = list(csv.DictReader(io.open(tpath, encoding="utf-8")))
        cols = set(rows[0].keys())
        for w in desc:
            if w in cols:
                support[w] = sum(
                    1 for r in rows
                    if (r.get(w) or "0") not in ("0", "", "0.0"))

    out_rows = []
    for j, w in enumerate(desc):
        carriers = int((Z[:, j] >= 2.0).sum())
        best = int(np.argmax(Z[:, j]))
        out_rows.append({
            "descriptor": w,
            "training_molecules": support.get(w, ""),
            "library_carriers": carriers,
            "strongest_carrier": names[best],
            "strongest_z": round(float(Z[best, j]), 1),
            "mean_probability": round(float(mu[j]), 4),
        })

    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out_rows[0]))
        w.writeheader()
        w.writerows(out_rows)

    thin = [r for r in out_rows
            if r["training_molecules"] != "" and r["training_molecules"] < 80]
    nocar = [r for r in out_rows if r["library_carriers"] == 0]
    lines = [
        f"# The {len(desc)} descriptors this model can predict",
        "",
        "Generated by `scripts/descriptor_list.py`. These are the only words a",
        "target can be written in: the percept model emits exactly these, so a",
        "quality absent from this list cannot be requested, however well it is",
        "described. Notably absent, and asked for: **marine**, **salty**,",
        "**seaweed**, **iodine**, **mineral**. Salt is non-volatile and has no",
        "odour at all, so that one is not a gap; the others are real qualities",
        "with no label, and the nearest available words are `ozone`, `fishy`,",
        "`sulfurous`, `metallic`, `earthy` and `musty`.",
        "",
        f"- **{len(thin)} of {len(desc)}** have fewer than 80 training",
        "  molecules, so a request for them is poorly supported.",
        f"- **{len(nocar)}** have no material scoring 2 sd above the library",
        "  mean. Read that carefully: for a rare descriptor it means nothing on",
        "  the shelf delivers it, but `floral` and `fruity` land here because",
        "  they are close to universal, so their spread is wide and no single",
        "  material stands out against it. A descriptor every material has a",
        "  little of cannot be asked for either, for the opposite reason.",
        "",
        "| descriptor | training molecules | library carriers | strongest carrier |",
        "|---|---:|---:|---|",
    ]
    for r in sorted(out_rows, key=lambda r: r["descriptor"]):
        flag = " ⚠" if (r["training_molecules"] != ""
                        and r["training_molecules"] < 80) else ""
        lines.append(f"| {r['descriptor']}{flag} | {r['training_molecules']} "
                     f"| {r['library_carriers']} | {r['strongest_carrier']} "
                     f"(z {r['strongest_z']:+.1f}) |")
    lines += ["", "⚠ = fewer than 80 training molecules.", ""]
    (ROOT / args.md).write_text("\n".join(lines), encoding="utf-8")

    print(f"wrote {args.out} and {args.md}")
    print(f"  {len(desc)} descriptors, {len(thin)} thinly trained, "
          f"{len(nocar)} with no carrier in the library")
    print(f"\n  thinnest: " + ", ".join(
        f"{r['descriptor']} ({r['training_molecules']})"
        for r in sorted(thin, key=lambda r: r["training_molecules"])[:10]))
    if nocar:
        print(f"  no material 2 sd above the mean: "
              + ", ".join(r["descriptor"] for r in nocar)
              + "  (for these two it is because almost everything scores on "
                "them, not because nothing does)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
